  function creaBrioche(svg, D) {
    var c01 = function (t) { return Math.max(0, Math.min(1, t)); };
    var r2 = function (n) { return Math.round(n * 100) / 100; };
    var r3 = function (n) { return Math.round(n * 1000) / 1000; };
    /* la fine di una fase arriva a 1 esatto (#256) */
    var fase = function (t, w) { return t >= w.t + w.d - 1e-9 ? 1 : c01((t - w.t) / w.d); };
    var dolce = function (u) { return u < .5 ? 4 * u * u * u : 1 - Math.pow(-2 * u + 2, 3) / 2; };
    var sacca = svg.querySelector('.sacca'), corpo = svg.querySelector('.sacca__corpo'), gonfio = svg.querySelector('.gonfio'), banco = svg.querySelector('.banco');
    var P = D.ripieni.map(function (_, m) {
      var q = function (s) { return svg.querySelector(s + '[data-m="' + m + '"]'); };
      var cop = q('.copertura');
      return { pieno: q('.sacca__pieno'), goccia: q('.goccia'), copertura: cop, striscia: cop ? cop.querySelector('.striscia') : null };
    });
    function disegna(m, t, v) {
      var F = D.fasi, q = P[m];
      /* la sacca: arriva dall'alto a destra, il beccuccio entra nella punta, poi esce e torna via */
      var x, y;
      if (t < F.entra.t) { var a = 1 - dolce(fase(t, F.arriva)); x = D.fuori[0] * a; y = D.fuori[1] * a; }
      else if (t < F.esce.t) { var e = dolce(fase(t, F.entra)); x = D.spinta[0] * e; y = D.spinta[1] * e; }
      else { var u = dolce(fase(t, F.esce)); x = D.spinta[0] * (1 - u) + D.fuori[0] * u; y = D.spinta[1] * (1 - u) + D.fuori[1] * u; }
      sacca.setAttribute('transform', 'translate(' + r2(x) + ' ' + r2(y) + ')');
      /* la sacca si stringe e si svuota, il cornetto si gonfia appena */
      var r = dolce(fase(t, F.riempie));
      corpo.setAttribute('transform', 'scale(' + r3(1 - D.stretta * r) + ' 1)');
      q.pieno.setAttribute('transform', 'translate(0 ' + r2(D.vuota * r) + ')');
      gonfio.setAttribute('transform', 'scale(' + r3(1 + D.gonfio * r) + ')');
      /* sulla punta resta una goccia di ripieno, poi cade la copertura */
      q.goccia.setAttribute('transform', 'scale(' + r3(dolce(fase(t, F.goccia))) + ')');
      var c = fase(t, F.copertura);
      q.copertura.setAttribute('opacity', String(r3(c)));
      q.copertura.setAttribute('transform', 'translate(0 ' + r2(-30 * Math.pow(1 - c, 2)) + ')');
      if (q.striscia) q.striscia.setAttribute('stroke-dashoffset', String(r3(1 - c)));
      /* col V il piatto esce a destra (V > 0) e quello nuovo arriva da destra (V < 0): non passa sopra la tazza */
      banco.setAttribute('transform', 'translate(' + r2(D.via * Math.abs(v)) + ' 0)');
    }
    var completo = !!sacca && !!corpo && !!gonfio && !!banco && P.every(function (q, m) { return q.pieno && q.goccia && q.copertura && (D.ripieni[m].sopra === 'pistacchio') === !!q.striscia; });
    return { disegna: disegna, pezzi: P, completo: completo };
  }

